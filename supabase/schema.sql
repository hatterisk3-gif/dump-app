create table if not exists public.inbox (
  id text primary key default (gen_random_uuid())::text,
  seq bigint generated by default as identity not null,
  created_at timestamptz not null default now(),
  content text not null,
  is_deleted boolean not null default false
);

create table if not exists public.data_records (
  id text primary key default (gen_random_uuid())::text,
  seq bigint generated by default as identity not null,
  created_at timestamptz not null default now(),
  folder text not null,
  file text not null default '',
  content text not null,
  is_deleted boolean not null default false
);

create table if not exists public.config_records (
  id bigint generated by default as identity primary key,
  folder text not null,
  file text not null default '',
  created_at timestamptz not null default now(),
  is_deleted boolean not null default false,
  constraint config_records_folder_file_key unique (folder, file)
);

create table if not exists public.sync_meta (
  id integer primary key check (id = 1),
  stamp text not null default ((extract(epoch from now()) * 1000)::bigint)::text,
  updated_at timestamptz not null default now()
);

insert into public.sync_meta (id)
values (1)
on conflict (id) do nothing;

