-- 6. RPC Entrypoints (dump_api_single / dump_api)
-- =========================================================
create or replace function public.dump_api_single(params jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_action text;
  v_id text;
  v_content text;
  v_folder text;
  v_file text;
  v_old_folder text;
  v_old_file text;
  v_new_folder text;
  v_new_file text;
  v_next_file text;
  v_kw text;
  v_stamp text;
  v_count int;
  v_ids jsonb;
  v_inbox jsonb;
  v_next_item jsonb;
  v_config jsonb;
  v_pending jsonb;
  v_grouped jsonb;
  v_items jsonb;
  v_matches jsonb;
  v_purged jsonb;
  v_to_trash jsonb;
  v_res jsonb;
  v_include_system boolean;
  v_include_trash boolean;
  v_cfg_row record;
begin
  if params is null or jsonb_typeof(params) <> 'object' then
    return jsonb_build_object('error', 'Invalid params');
  end if;

  v_action := params->>'action';

  if v_action = 'addInbox' then
    v_content := params->>'content';
    if v_content is null or public.js_trim(v_content) = '' then
      return jsonb_build_object('success', false);
    end if;
    insert into public.inbox (id, created_at, content, is_deleted)
    values (gen_random_uuid()::text, now(), v_content, false);
    return jsonb_build_object('success', true);

  elsif v_action = 'addManyInbox' then
    with req as (
      select arr_t.elem, arr_t.ord
      from jsonb_array_elements_text(
        case when jsonb_typeof(params->'contents') = 'array' then params->'contents' else '[]'::jsonb end
      ) with ordinality as arr_t(elem, ord)
      where arr_t.elem is not null and public.js_trim(arr_t.elem) <> ''
      order by arr_t.ord asc
    ),
    inserted as (
      insert into public.inbox (id, created_at, content, is_deleted)
      select gen_random_uuid()::text, now(), req.elem, false
      from req
      order by req.ord asc
      returning id, seq
    )
    select count(*)::int, coalesce(jsonb_agg(to_jsonb(inserted.id) order by inserted.seq asc), '[]'::jsonb)
    into v_count, v_ids
    from inserted;
    return jsonb_build_object(
      'success', true,
      'count', coalesce(v_count, 0),
      'ids', coalesce(v_ids, '[]'::jsonb)
    );

  elsif v_action = 'getOrganizerData' then
    select count(*)::int into v_count
    from public.inbox
    where not is_deleted;

    select jsonb_build_object('id', ibx.id, 'content', ibx.content)
    into v_next_item
    from public.inbox ibx
    where not ibx.is_deleted
    order by ibx.seq asc
    limit 1;

    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', ibx.id,
          'timestamp', ibx.created_at,
          'content', ibx.content
        )
        order by ibx.seq asc
      ),
      '[]'::jsonb
    )
    into v_inbox
    from public.inbox ibx
    where not ibx.is_deleted;

    with active_cfg as (
      select id, folder, file
      from public.config_records
      where not is_deleted and folder is not null and folder <> ''
    ),
    dedup as (
      select folder, file, min(id) as min_id
      from active_cfg
      group by folder, file
    ),
    by_folder as (
      select
        folder,
        coalesce(
          jsonb_agg(to_jsonb(file) order by min_id asc) filter (where file is not null and file <> ''),
          '[]'::jsonb
        ) as files
      from dedup
      group by folder
    )
    select coalesce(jsonb_object_agg(folder, files), '{}'::jsonb)
    into v_config
    from by_folder;

    return jsonb_build_object(
      'count', coalesce(v_count, 0),
      'nextItem', v_next_item,
      'config', v_config,
      'inbox', coalesce(v_inbox, '[]'::jsonb)
    );

  elsif v_action = 'getReviewOverview' then
    v_res := public.dump_api_single(jsonb_build_object('action', 'getOrganizerData'));
    select coalesce(jsonb_object_agg(pending_sub.folder, pending_sub.items), '{}'::jsonb)
    into v_pending
    from (
      select folder,
             jsonb_agg(
               jsonb_build_object(
                 'id', id,
                 'timestamp', public.format_jst_date(created_at),
                 'content', content
               )
               order by seq asc
             ) as items
      from public.data_records
      where not is_deleted
        and folder is not null
        and folder <> ''
        and file = '未整理'
      group by folder
    ) pending_sub;
    return jsonb_build_object(
      'organizer', v_res,
      'pendingByFolder', v_pending
    );

  elsif v_action = 'moveInboxItem' then
    v_res := public.dump_api_single(
      jsonb_build_object(
        'action', 'moveInboxItems',
        'items', jsonb_build_array(
          jsonb_build_object(
            'id', params->'id',
            'folder', params->'folder',
            'file', params->'file'
          )
        )
      )
    );
    v_count := coalesce((v_res->>'count')::int, 0);
    if v_count = 0 then
      return jsonb_build_object('error', 'Error: Item not found');
    end if;
    return jsonb_build_object('success', true, 'count', v_count);

  elsif v_action = 'moveInboxItems' then
    with req as (
      select distinct on (arr_t.elem->>'id')
        arr_t.elem->>'id' as id,
        coalesce(arr_t.elem->>'folder', '') as folder,
        coalesce(arr_t.elem->>'file', '') as file
      from jsonb_array_elements(
        case when jsonb_typeof(params->'items') = 'array' then params->'items' else '[]'::jsonb end
      ) with ordinality as arr_t(elem, ord)
      where jsonb_typeof(arr_t.elem) = 'object'
        and arr_t.elem ? 'id'
        and nullif(arr_t.elem->>'id', '') is not null
      order by arr_t.elem->>'id', arr_t.ord desc
    ),
    matched as (
      select ibx.id, ibx.seq, ibx.content, req_row.folder, req_row.file
      from public.inbox ibx
      join req req_row on req_row.id = ibx.id
      where not ibx.is_deleted
      order by ibx.seq asc
    ),
    inserted as (
      insert into public.data_records (id, created_at, folder, file, content, is_deleted)
      select matched_row.id, now(), matched_row.folder, matched_row.file, matched_row.content, false
      from matched matched_row
      order by matched_row.seq asc
      on conflict (id) do update
        set created_at = excluded.created_at,
            folder = excluded.folder,
            file = excluded.file,
            content = excluded.content,
            is_deleted = false
      returning id
    ),
    marked as (
      update public.inbox ibx
      set is_deleted = true
      from inserted ins_row
      where ibx.id = ins_row.id
        and not ibx.is_deleted
      returning ibx.id
    )
    select count(*)::int into v_count from marked;

    return jsonb_build_object('success', true, 'count', coalesce(v_count, 0));

  elsif v_action = 'updateInbox' then
    v_id := nullif(params->>'id', '');
    v_content := params->>'content';
    if v_id is null or v_content is null or public.js_trim(v_content) = '' then
      return jsonb_build_object('success', false, 'error', 'invalid');
    end if;
    update public.inbox
    set created_at = now(),
        content = v_content
    where id = v_id
      and not is_deleted;
    if found then
      return jsonb_build_object('success', true, 'id', v_id);
    end if;
    return jsonb_build_object('success', false, 'error', 'not_found');

  elsif v_action = 'updateDataRecord' then
    v_id := nullif(params->>'id', '');
    v_content := params->>'content';
    v_folder := nullif(params->>'folder', '');
    v_file := nullif(params->>'file', '');
    if v_id is null or v_content is null or public.js_trim(v_content) = '' then
      return jsonb_build_object('success', false, 'error', 'invalid');
    end if;
    update public.data_records
    set created_at = now(),
        folder = coalesce(v_folder, folder),
        file = coalesce(v_file, file),
        content = v_content
    where id = v_id
      and not is_deleted;
    if found then
      return jsonb_build_object('success', true, 'id', v_id);
    end if;
    return jsonb_build_object('success', false, 'error', 'not_found');

  elsif v_action = 'findExactContentsInData' then
    with req as (
      select distinct on (public.js_trim(arr_t.val))
        public.js_trim(arr_t.val) as key,
        arr_t.ord
      from jsonb_array_elements_text(
        case when jsonb_typeof(params->'contents') = 'array' then params->'contents' else '[]'::jsonb end
      ) with ordinality as arr_t(val, ord)
      where arr_t.val is not null and public.js_trim(arr_t.val) <> ''
      order by public.js_trim(arr_t.val), arr_t.ord asc
    ),
    existing as (
      select distinct public.js_trim(content) as key
      from public.data_records
      where not is_deleted
        and not public.is_excluded_data_location(folder)
        and public.js_trim(content) <> ''
    )
    select coalesce(jsonb_agg(to_jsonb(req_row.key) order by req_row.ord asc), '[]'::jsonb)
    into v_matches
    from req req_row
    join existing ext_row on ext_row.key = req_row.key;
    return jsonb_build_object('matches', coalesce(v_matches, '[]'::jsonb));

  elsif v_action = 'purgeInboxExactDuplicates' then
    with existing as (
      select distinct public.js_trim(content) as key
      from public.data_records
      where not is_deleted
        and not public.is_excluded_data_location(folder)
        and public.js_trim(content) <> ''
    ),
    dups as (
      select ibx.id, ibx.seq, public.js_trim(ibx.content) as key
      from public.inbox ibx
      join existing ext_row on ext_row.key = public.js_trim(ibx.content)
      where not ibx.is_deleted
        and public.js_trim(ibx.content) <> ''
      order by ibx.seq asc
    )
    select
      coalesce(
        jsonb_agg(
          jsonb_build_object('id', id, 'folder', '🗑️ ゴミ箱', 'file', '削除履歴')
          order by seq asc
        ),
        '[]'::jsonb
      ),
      coalesce(jsonb_agg(to_jsonb(key) order by seq asc), '[]'::jsonb)
    into v_to_trash, v_purged
    from dups;

    if jsonb_array_length(v_to_trash) = 0 then
      return jsonb_build_object('success', true, 'count', 0, 'purgedContents', '[]'::jsonb);
    end if;

    v_res := public.dump_api_single(jsonb_build_object('action', 'moveInboxItems', 'items', v_to_trash));
    return jsonb_build_object(
      'success', coalesce((v_res->>'success')::boolean, false),
      'count', coalesce((v_res->>'count')::int, 0),
      'purgedContents', coalesce(v_purged, '[]'::jsonb)
    );

  elsif v_action = 'searchItems' then
    v_kw := lower(public.js_trim(params->>'keyword'));
    if v_kw = '' then
      return '[]'::jsonb;
    end if;
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', id,
          'timestamp', public.format_jst_date(created_at),
          'folder', folder,
          'file', file,
          'content', content,
          'isInbox', false
        )
        order by created_at desc, seq desc
      ),
      '[]'::jsonb
    )
    into v_res
    from public.data_records
    where not is_deleted
      and not public.is_excluded_data_location(folder)
      and coalesce(file, '') <> '削除履歴'
      and (
        position(v_kw in lower(coalesce(folder, ''))) > 0
        or position(v_kw in lower(coalesce(file, ''))) > 0
        or position(v_kw in lower(coalesce(content, ''))) > 0
      );
    return coalesce(v_res, '[]'::jsonb);

  elsif v_action = 'searchData' then
    v_kw := lower(public.js_trim(params->>'keyword'));
    if v_kw = '' then
      return '[]'::jsonb;
    end if;
    with combined as (
      select
        id,
        created_at,
        seq,
        0 as src_rank,
        'INBOX'::text as folder,
        '未整理'::text as file,
        content,
        true as is_inbox
      from public.inbox
      where not is_deleted
        and position(v_kw in lower(coalesce(content, ''))) > 0
      union all
      select
        id,
        created_at,
        seq,
        1 as src_rank,
        folder,
        file,
        content,
        false as is_inbox
      from public.data_records
      where not is_deleted
        and not public.is_excluded_data_location(folder)
        and coalesce(file, '') <> '削除履歴'
        and (
          position(v_kw in lower(coalesce(folder, ''))) > 0
          or position(v_kw in lower(coalesce(file, ''))) > 0
          or position(v_kw in lower(coalesce(content, ''))) > 0
        )
    )
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', id,
          'timestamp', public.format_jst_date(created_at),
          'folder', folder,
          'file', file,
          'content', content,
          'isInbox', is_inbox
        )
        order by created_at desc, src_rank asc, seq desc
      ),
      '[]'::jsonb
    )
    into v_res
    from combined;
    return coalesce(v_res, '[]'::jsonb);

  elsif v_action = 'getConfigList' then
    select coalesce(
      jsonb_agg(
        jsonb_build_object('folder', folder, 'file', file)
        order by id asc
      ),
      '[]'::jsonb
    )
    into v_res
    from public.config_records
    where not is_deleted
      and (folder <> '' or file <> '');
    return coalesce(v_res, '[]'::jsonb);

  elsif v_action = 'addConfigRecord' then
    v_folder := public.js_trim(params->>'folder');
    v_file := public.js_trim(params->>'file');
    if v_folder = '' then
      return jsonb_build_object('success', false);
    end if;
    insert into public.config_records (folder, file, is_deleted)
    values (v_folder, v_file, false)
    on conflict (folder, file) do update
      set is_deleted = false;
    return jsonb_build_object('success', true);

  elsif v_action = 'deleteConfigRecord' then
    v_folder := coalesce(params->>'folder', '');
    v_file := coalesce(params->>'file', '');
    update public.config_records
    set is_deleted = true
    where not is_deleted
      and folder = v_folder
      and file = v_file;
    return jsonb_build_object('success', true);

  elsif v_action = 'updateConfigRecord' then
    v_old_folder := coalesce(params->>'oldFolder', '');
    v_old_file := coalesce(params->>'oldFile', '');
    v_new_folder := public.js_trim(params->>'newFolder');
    v_new_file := public.js_trim(params->>'newFile');
    if v_new_folder = '' then
      return jsonb_build_object('success', false);
    end if;
    if v_old_file <> '' and v_new_file = '' then
      return jsonb_build_object('success', false);
    end if;

    for v_cfg_row in
      select id, folder, file
      from public.config_records
      where not is_deleted
        and folder = v_old_folder
        and (v_old_file = '' or file = v_old_file)
      order by id asc
    loop
      v_next_file := case when v_old_file = '' and v_new_file = '' then v_cfg_row.file else v_new_file end;
      if v_cfg_row.folder <> v_new_folder or v_cfg_row.file <> v_next_file then
        update public.config_records
        set is_deleted = true
        where id = v_cfg_row.id;

        insert into public.config_records (folder, file, is_deleted)
        values (v_new_folder, v_next_file, false)
        on conflict (folder, file) do update
          set is_deleted = false;
      end if;
    end loop;

    update public.data_records
    set folder = v_new_folder,
        file = case when v_old_file = '' and v_new_file = '' then file else v_new_file end
    where not is_deleted
      and folder = v_old_folder
      and (v_old_file = '' or file = v_old_file);

    return jsonb_build_object('success', true);

  elsif v_action = 'getFolderFileItems' then
    v_folder := coalesce(params->>'folder', '');
    v_file := coalesce(params->>'file', '');
    select coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', id,
          'timestamp', public.format_jst_date(created_at),
          'content', content
        )
        order by seq asc
      ),
      '[]'::jsonb
    )
    into v_res
    from public.data_records
    where not is_deleted
      and folder = v_folder
      and file = v_file;
    return coalesce(v_res, '[]'::jsonb);

  elsif v_action = 'getAllDataGrouped' then
    v_include_system := coalesce((params->>'includeSystem')::boolean, false);
    v_include_trash := coalesce((params->>'includeTrash')::boolean, false);

    with filtered as (
      select id, seq, created_at, folder, coalesce(file, '') as file, content
      from public.data_records
      where not is_deleted
        and folder is not null
        and folder <> ''
        and (v_include_trash or position('ゴミ箱' in folder) = 0)
        and (v_include_system or folder <> '__SYSTEM__')
    ),
    by_file as (
      select
        folder,
        file,
        jsonb_agg(
          jsonb_build_object(
            'id', id,
            'timestamp', public.format_jst_date(created_at),
            'content', content
          )
          order by seq asc
        ) as entries
      from filtered
      group by folder, file
    ),
    by_folder as (
      select
        folder,
        jsonb_object_agg(file, entries) as files_obj
      from by_file
      group by folder
    )
    select
      coalesce((select jsonb_object_agg(folder, files_obj) from by_folder), '{}'::jsonb),
      coalesce((
        select jsonb_agg(
          jsonb_build_object(
            'id', id,
            'timestamp', public.format_jst_date(created_at),
            'content', content,
            'folder', folder,
            'file', file
          )
          order by seq asc
        )
        from filtered
      ), '[]'::jsonb)
    into v_grouped, v_items;

    return jsonb_build_object(
      'grouped', v_grouped,
      'items', v_items
    );

  elsif v_action = 'getSyncStamp' then
    select stamp into v_stamp from public.sync_meta where id = 1;
    return jsonb_build_object(
      'stamp', coalesce(v_stamp, '0'),
      'imageApi', 3
    );

  elsif v_action = 'deleteDataRecord' then
    if params ? 'id' and params->'id' <> 'null'::jsonb and nullif(params->>'id', '') is not null then
      return public.dump_api_single(
        jsonb_build_object('action', 'deleteDataRecords', 'ids', jsonb_build_array(params->'id'))
      );
    end if;
    return jsonb_build_object('success', true, 'count', 0);

  elsif v_action = 'deleteDataRecords' then
    with ids_req as (
      select distinct arr_t.elem as id
      from jsonb_array_elements_text(
        case when jsonb_typeof(params->'ids') = 'array' then params->'ids' else '[]'::jsonb end
      ) as arr_t(elem)
      where arr_t.elem is not null and arr_t.elem <> ''
    ),
    updated as (
      update public.data_records dat
      set folder = '🗑️ ゴミ箱',
          file = '削除履歴'
      from ids_req req_row
      where dat.id = req_row.id
        and not dat.is_deleted
      returning dat.id
    )
    select count(*)::int into v_count from updated;
    return jsonb_build_object('success', true, 'count', coalesce(v_count, 0));

  elsif v_action = 'purgeSystemTrash' then
    update public.data_records
    set is_deleted = true
    where not is_deleted
      and public.is_system_snapshot_trash_row(folder, file, content);
    get diagnostics v_count = row_count;
    return jsonb_build_object('success', true, 'count', coalesce(v_count, 0));

  elsif v_action = 'addDataRecord' then
    v_content := params->>'content';
    if v_content is null or public.js_trim(v_content) = '' then
      return jsonb_build_object('success', false);
    end if;
    v_id := gen_random_uuid()::text;
    insert into public.data_records (id, created_at, folder, file, content, is_deleted)
    values (
      v_id,
      now(),
      coalesce(params->>'folder', ''),
      coalesce(params->>'file', ''),
      v_content,
      false
    );
    return jsonb_build_object('success', true, 'id', v_id);

  elsif v_action = 'addManyDataRecords' then
    with req as (
      select
        coalesce(arr_t.elem->>'folder', '') as folder,
        coalesce(arr_t.elem->>'file', '') as file,
        arr_t.elem->>'content' as content,
        arr_t.ord
      from jsonb_array_elements(
        case when jsonb_typeof(params->'items') = 'array' then params->'items' else '[]'::jsonb end
      ) with ordinality as arr_t(elem, ord)
      where jsonb_typeof(arr_t.elem) = 'object'
        and arr_t.elem ? 'content'
        and (arr_t.elem->>'content') is not null
        and public.js_trim(arr_t.elem->>'content') <> ''
      order by arr_t.ord asc
    ),
    inserted as (
      insert into public.data_records (id, created_at, folder, file, content, is_deleted)
      select gen_random_uuid()::text, now(), req.folder, req.file, req.content, false
      from req
      order by req.ord asc
      returning id, seq
    )
    select count(*)::int, coalesce(jsonb_agg(to_jsonb(inserted.id) order by inserted.seq asc), '[]'::jsonb)
    into v_count, v_ids
    from inserted;
    return jsonb_build_object(
      'success', true,
      'count', coalesce(v_count, 0),
      'ids', coalesce(v_ids, '[]'::jsonb)
    );

  elsif v_action = 'moveDataRecord' then
    v_id := nullif(params->>'id', '');
    if v_id is null then
      return jsonb_build_object('success', false);
    end if;
    update public.data_records
    set folder = coalesce(params->>'folder', ''),
        file = coalesce(params->>'file', '')
    where id = v_id
      and not is_deleted;
    return jsonb_build_object('success', found);

  elsif v_action = 'moveDataRecords' then
    with req as (
      select distinct on (arr_t.elem->>'id')
        arr_t.elem->>'id' as id,
        coalesce(arr_t.elem->>'folder', '') as folder,
        coalesce(arr_t.elem->>'file', '') as file
      from jsonb_array_elements(
        case when jsonb_typeof(params->'items') = 'array' then params->'items' else '[]'::jsonb end
      ) with ordinality as arr_t(elem, ord)
      where jsonb_typeof(arr_t.elem) = 'object'
        and arr_t.elem ? 'id'
        and nullif(arr_t.elem->>'id', '') is not null
      order by arr_t.elem->>'id', arr_t.ord desc
    ),
    updated as (
      update public.data_records dat
      set folder = req_row.folder,
          file = req_row.file
      from req req_row
      where dat.id = req_row.id
        and not dat.is_deleted
      returning dat.id
    )
    select count(*)::int into v_count from updated;
    return jsonb_build_object('success', true, 'count', coalesce(v_count, 0));

  elsif v_action = 'keepWarm' then
    select stamp into v_stamp from public.sync_meta where id = 1;
    return jsonb_build_object(
      'success', true,
      'warm', true,
      'stamp', coalesce(v_stamp, '0')
    );

  else
    return jsonb_build_object('error', 'Unknown action: ' || coalesce(v_action, ''));
  end if;
end;
$$;

create or replace function public.dump_api(payload jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_action text;
  v_ops jsonb;
  v_op jsonb;
  v_res jsonb;
  v_results jsonb := '[]'::jsonb;
  v_has_error boolean := false;
begin
  if payload is null or jsonb_typeof(payload) <> 'object' then
    return jsonb_build_object('error', 'Missing payload');
  end if;

  v_action := payload->>'action';
  if v_action = 'batch' then
    v_ops := case when jsonb_typeof(payload->'ops') = 'array' then payload->'ops' else '[]'::jsonb end;
    for v_op in select value from jsonb_array_elements(v_ops)
    loop
      begin
        v_res := public.dump_api_single(coalesce(v_op, '{}'::jsonb));
      exception when others then
        v_res := jsonb_build_object('error', sqlerrm);
      end;
      if v_res is not null and (v_res ? 'error') then
        v_has_error := true;
      end if;
      v_results := v_results || jsonb_build_array(coalesce(v_res, '{}'::jsonb));
    end loop;
    return jsonb_build_object('success', not v_has_error, 'results', v_results);
  end if;

  return public.dump_api_single(payload);
end;
$$;

