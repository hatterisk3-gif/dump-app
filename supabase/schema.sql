-- 2. Helpers (Immutable functions used by partial indexes)
-- =========================================================
create or replace function public.js_trim(val text)
returns text
language sql
immutable
set search_path = public
as $$
  select btrim(coalesce(val, ''), E' \t\r\n\f\v\u00a0\u3000');
$$;

create or replace function public.format_jst_date(ts timestamptz)
returns text
language sql
immutable
set search_path = public
as $$
  select coalesce(to_char(ts at time zone 'Asia/Tokyo', 'YYYY/MM/DD HH24:MI'), '');
$$;

create or replace function public.is_excluded_data_location(p_folder text)
returns boolean
language sql
immutable
set search_path = public
as $$
  select p_folder is null
      or p_folder = ''
      or p_folder = '__SYSTEM__'
      or p_folder = '🗑️ ゴミ箱'
      or position('ゴミ箱' in p_folder) > 0;
$$;

create or replace function public.is_system_snapshot_trash_row(
  p_folder text,
  p_file text,
  p_content text
)
returns boolean
language plpgsql
immutable
set search_path = public
as $$
declare
  v_text text;
  v_obj jsonb;
begin
  if coalesce(p_folder, '') <> '🗑️ ゴミ箱' or coalesce(p_file, '') <> '削除履歴' then
    return false;
  end if;
  v_text := public.js_trim(p_content);
  if v_text = '' or left(v_text, 1) <> '{' or right(v_text, 1) <> '}' then
    return false;
  end if;
  begin
    v_obj := v_text::jsonb;
  exception when others then
    return false;
  end;
  if v_obj is null or jsonb_typeof(v_obj) <> 'object' then
    return false;
  end if;
  if (v_obj ? 'content') or (v_obj ? 'folder') or (v_obj ? 'file') then
    return false;
  end if;
  if jsonb_typeof(v_obj->'v') <> 'number' or jsonb_typeof(v_obj->'updatedAt') <> 'string' then
    return false;
  end if;
  return (v_obj ?| array['library', 'tasks', 'favorites', 'profiles', 'startAt', 'masters', 'intakes', 'routines']);
end;
$$;

