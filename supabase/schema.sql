-- 5. Sync Stamp Trigger
-- =========================================================
create or replace function public.touch_sync_meta()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  insert into public.sync_meta (id, stamp, updated_at)
  values (1, ((extract(epoch from clock_timestamp()) * 1000)::bigint)::text, clock_timestamp())
  on conflict (id) do update
    set stamp = excluded.stamp,
        updated_at = excluded.updated_at;
  return null;
end;
$$;

drop trigger if exists trg_inbox_touch_sync_meta on public.inbox;
create trigger trg_inbox_touch_sync_meta
  after insert or update or delete on public.inbox
  for each statement execute function public.touch_sync_meta();

drop trigger if exists trg_data_records_touch_sync_meta on public.data_records;
create trigger trg_data_records_touch_sync_meta
  after insert or update or delete on public.data_records
  for each statement execute function public.touch_sync_meta();

drop trigger if exists trg_config_records_touch_sync_meta on public.config_records;
create trigger trg_config_records_touch_sync_meta
  after insert or update or delete on public.config_records
  for each statement execute function public.touch_sync_meta();

